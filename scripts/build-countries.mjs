// Builds src/data/countries.js for the /global outline game.
// Source: Natural Earth 1:50m country shapes (public domain) via the world-atlas package.
// Run: npm run build:countries
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { feature } from 'topojson-client'
import { geoArea, geoCentroid, geoDistance, geoAzimuthalEqualArea, geoPath } from 'd3-geo'

const require = createRequire(import.meta.url)
const world = JSON.parse(readFileSync(require.resolve('world-atlas/countries-50m.json'), 'utf8'))

// Territories, dependencies and disputed areas left out of the guess list.
const skip = new Set([
  'N. Mariana Is.', 'U.S. Virgin Is.', 'Guam', 'American Samoa', 'Puerto Rico', 'S. Geo. and the Is.',
  'Br. Indian Ocean Ter.', 'Saint Helena', 'Pitcairn Is.', 'Anguilla', 'Falkland Is.', 'Cayman Is.', 'Bermuda',
  'British Virgin Is.', 'Turks and Caicos Is.', 'Montserrat', 'Jersey', 'Guernsey', 'Isle of Man', 'Somaliland',
  'Niue', 'Cook Is.', 'Aruba', 'Curaçao', 'W. Sahara', 'Macao', 'Hong Kong', 'St. Pierre and Miquelon',
  'Wallis and Futuna Is.', 'St-Martin', 'St-Barthélemy', 'Fr. Polynesia', 'New Caledonia', 'Fr. S. Antarctic Lands',
  'Åland', 'Greenland', 'Faeroe Is.', 'N. Cyprus', 'Indian Ocean Ter.', 'Heard I. and McDonald Is.',
  'Norfolk Island', 'Ashmore and Cartier Is.', 'Siachen Glacier', 'Antarctica', 'Sint Maarten',
])

// Natural Earth abbreviates some names; spell them out.
const rename = {
  'Marshall Is.': 'Marshall Islands',
  'United States of America': 'United States',
  eSwatini: 'Eswatini',
  'S. Sudan': 'South Sudan',
  'Solomon Is.': 'Solomon Islands',
  'São Tomé and Principe': 'São Tomé and Príncipe',
  'St. Vin. and Gren.': 'Saint Vincent and the Grenadines',
  'St. Kitts and Nevis': 'Saint Kitts and Nevis',
  Macedonia: 'North Macedonia',
  'Eq. Guinea': 'Equatorial Guinea',
  'Dominican Rep.': 'Dominican Republic',
  'Dem. Rep. Congo': 'Democratic Republic of the Congo',
  Congo: 'Republic of the Congo',
  'Central African Rep.': 'Central African Republic',
  'Bosnia and Herz.': 'Bosnia and Herzegovina',
  'Antigua and Barb.': 'Antigua and Barbuda',
  Vatican: 'Vatican City',
}

const EARTH_KM2 = 6371 ** 2
const MIN_AREA_KM2 = 20000 // smaller countries can be guessed but are never the answer
const MAX_SPREAD = (40 * Math.PI) / 180 // drop far-off parts (overseas territories, remote islands)
const SIZE = 300 // outline viewBox is SIZE × SIZE

const polygonsOf = (g) => (g.type === 'Polygon' ? [g.coordinates] : g.coordinates)
const round = (n) => Math.round(n * 100) / 100

// Shrinks a whole-pixel SVG path: drops repeated points and specks too small to see.
function compact(path) {
  return path
    .split('M')
    .filter(Boolean)
    .map((ring) => {
      const points = ring.replace(/Z$/, '').split('L')
      return points.filter((pt, i) => pt !== points[(i + 1) % points.length])
    })
    .filter((points) => {
      const xs = points.map((pt) => +pt.split(',')[0])
      const ys = points.map((pt) => +pt.split(',')[1])
      return points.length >= 3 && (Math.max(...xs) - Math.min(...xs)) * (Math.max(...ys) - Math.min(...ys)) >= 4
    })
    .map((points) => `M${points.join('L')}Z`)
    .join('')
}

const countries = []
for (const f of feature(world, world.objects.countries).features) {
  if (skip.has(f.properties.name)) continue
  const name = rename[f.properties.name] ?? f.properties.name

  // Keep the main landmass plus anything near it.
  const parts = polygonsOf(f.geometry)
    .map((coordinates) => ({ type: 'Polygon', coordinates }))
    .sort((a, b) => geoArea(b) - geoArea(a))
  const home = geoCentroid(parts[0])
  const kept = parts.filter((p) => geoDistance(home, geoCentroid(p)) <= MAX_SPREAD)
  const shape = { type: 'MultiPolygon', coordinates: kept.map((p) => p.coordinates) }
  const [lon, lat] = geoCentroid(shape)
  const entry = { name, lat: round(lat), lon: round(lon) }

  if (geoArea(shape) * EARTH_KM2 >= MIN_AREA_KM2) {
    // Each outline gets its own projection, centred on the country, so shapes are not distorted.
    const projection = geoAzimuthalEqualArea().rotate([-lon, -lat]).fitExtent([[6, 6], [SIZE - 6, SIZE - 6]], shape)
    entry.path = compact(geoPath(projection.precision(0.3)).digits(0)(shape))
  }
  countries.push(entry)
}
countries.sort((a, b) => a.name.localeCompare(b.name))

const out = `// GENERATED by scripts/build-countries.mjs (npm run build:countries). Do not edit by hand.
// Country outlines: Natural Earth (public domain). \`path\` is an SVG path in a ${SIZE}×${SIZE} box;
// countries without one are too small to be an answer but can still be guessed.
export const outlineSize = ${SIZE}

export const countries = ${JSON.stringify(countries)}
`
const file = new URL('../src/data/countries.js', import.meta.url)
writeFileSync(file, out)
console.log(`${countries.length} countries, ${countries.filter((c) => c.path).length} with outlines, ${(out.length / 1024).toFixed(0)} KB`)
